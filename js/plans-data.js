function fcPlanByKey(k) { return FC_PLANS.find(function (p) { return p.key === k; }) || FC_PLANS[0]; }
function fcPlanCompareHtml(current) {
  var cell = function (v) {
    if (v === 1) return '<i class="fas fa-check" style="color:#10b981"></i>';
    if (v === 0) return '<i class="fas fa-minus" style="color:#55627a"></i>';
    return '<span style="font-size:.82rem;color:#cfa776;font-weight:700">' + v + '</span>';
  };
  var head = FC_PLANS.map(function (p) {
    return '<th style="text-align:center;' + (p.key === current ? 'background:rgba(180,133,84,.22)' : '') + '">' + p.name + '<div style="font-size:.78rem;color:#aab7d4;font-weight:500">' + p.price + ' $ / سنوياً</div></th>';
  }).join('');
  var rows = FC_PLAN_ROWS.map(function (r) {
    return '<tr><td>' + r[0] + '</td>' + [1, 2, 3].map(function (i) { return '<td style="text-align:center">' + cell(r[i]) + '</td>'; }).join('') + '</tr>';
  }).join('');
  return '<div class="table-container" style="padding:0 0 6px"><table><thead><tr><th style="text-align:right">الميزة</th>' + head + '</tr></thead><tbody>' + rows + '</tbody></table></div>';
}
